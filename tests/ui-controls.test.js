'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname,'..');
const read = p => fs.readFileSync(path.join(root,p),'utf8');
const html=read('index.html');
const picker=read('period-picker.js');
const datedCss=read('dated.css');
const pngCss=read('png.css');
const extension=read('extension/content.js');
const core=read('extension/core.js');
assert.doesNotMatch(html, /id="period(?:Prev|Next)"/);
assert.doesNotMatch(picker, /data-png-period-(?:prev|next)/);
assert.doesNotMatch(extension, /gitbragPeriod(?:Previous|Next)/);
assert.match(datedCss,/\.period-stepper\.periods\s*\{[^}]*grid-template-columns:\s*minmax\(0,\s*1fr\)/s);
assert.match(pngCss,/\.png-unified-period-control\s*\{[^}]*grid-template-columns:\s*minmax\(0,\s*1fr\)/s);
assert.match(html, /id="repoView"/);
assert.match(html, /src="repo\.js\?v=/);
assert.match(html, /data-repo-module="metrics"/);
assert.match(core, /repositoryFromPath/);
assert.match(extension, /gitbrag:load-repository/);
console.log('period controls and repository integration checks passed');
